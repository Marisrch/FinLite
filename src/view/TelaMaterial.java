    private void btn_CadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_CadastrarActionPerformed

        try {

            String nome = txt_Nome_Material.getText();

            String cor = txt_Cor_Material.getText();

            String marca = txt_marca.getText();

            double custo = Double.parseDouble(txt_Custo_Unitario.getText());

            double quantidade = Double.parseDouble(txt_Quantidade_Estoque_Material.getText());

            String unidade = txt_Unidade_Medida.getText();

            MaterialController controller = new MaterialController();

            controller.salvarMaterial(
                    nome,
                    cor,
                    marca,
                    custo,
                    quantidade,
                    unidade
            );

            JOptionPane.showMessageDialog(
                    null,
                    "Material cadastrado com sucesso!"
            );

            carregarTabela();

            limparCampos();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    null,
                    "Erro: " + e.getMessage()
            );
        }
    }//GEN-LAST:event_btn_CadastrarActionPerformed

    private void btn_ExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_ExcluirActionPerformed

        try {

            int resposta = JOptionPane.showConfirmDialog(null, "Deseja excluir este material?");

            if (resposta == JOptionPane.YES_OPTION) {

                MaterialController controller
                        = new MaterialController();

                controller.excluirMaterial(idMaterialSelecionado);

                JOptionPane.showMessageDialog(null, "Material excluído!");

                carregarTabela();

                limparCampos();
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_btn_ExcluirActionPerformed

