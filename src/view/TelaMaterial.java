    public void carregarTabela() {

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();

        modelo.setRowCount(0);

        MaterialDAO dao
                = new MaterialDAO();

        ArrayList<Material> lista
                = dao.listarMateriais();

        for (Material m : lista) {

            modelo.addRow(new Object[]{
                m.getIdMaterial(),
                m.getNomeMaterial(),
                m.getCorMaterial(),
                m.getMarcaMaterial(),
                m.getCustoUnitarioMaterial(),
                m.getQuantidadeEstoqueMaterial(),
                m.getUnidadeMedidaMaterial()
            });
        }
    }

