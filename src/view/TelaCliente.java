    private void btn_CadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_CadastrarActionPerformed
        try {

            String nome = txt_nome.getText();

            String telefone = txt_telefone.getText();

            String cpf = txt_cpf.getText();

            ClienteController controller = new ClienteController();

            controller.salvarCliente(nome, telefone, cpf);

            JOptionPane.showMessageDialog(null, "Cliente cadastrado!");

            carregarTabela();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_btn_CadastrarActionPerformed

    private void tabela_clienteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabela_clienteMouseClicked

        int linha = tabela_cliente.getSelectedRow();

        idClienteSelecionado = Integer.parseInt(tabela_cliente.getValueAt(linha, 0).toString());

        txt_nome.setText(tabela_cliente.getValueAt(linha, 1).toString());

        txt_telefone.setText(tabela_cliente.getValueAt(linha, 2).toString());

        txt_cpf.setText(tabela_cliente.getValueAt(linha, 3).toString());
    }//GEN-LAST:event_tabela_clienteMouseClicked

    private void btn_EditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_EditarActionPerformed
        try {

            Cliente cliente = new Cliente();

            cliente.setIdCliente(idClienteSelecionado);

            cliente.setNomeCliente(txt_nome.getText());

            cliente.setTelefoneCliente(txt_telefone.getText());

            cliente.setCpfCliente(txt_cpf.getText());

            ClienteDAO dao = new ClienteDAO();

            dao.atualizarCliente(cliente);

            JOptionPane.showMessageDialog(null, "Cliente atualizado!");

            carregarTabela();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_btn_EditarActionPerformed

    private void btn_ExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_ExcluirActionPerformed
        try {

            int resposta = JOptionPane.showConfirmDialog(null, "Deseja excluir este cliente?");

            if (resposta == JOptionPane.YES_OPTION) {

                ClienteDAO dao = new ClienteDAO();

                dao.excluirCliente(idClienteSelecionado);

                JOptionPane.showMessageDialog(null, "Cliente excluído!");

                carregarTabela();
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_btn_ExcluirActionPerformed

